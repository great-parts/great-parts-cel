using System.Text;

namespace Great.Parts.Cel.Generator;

// The text of a created file: a file-local class whose module initializer registers one anonymous type with CelAnonymousData. The
// example is an anonymous object of the same names, types and order as the type of the call, so the compiler gives it that type;
// the declaration and the binding read each property by its name, so the created code has no reflection.
//
// A property of a row that cannot fail is bound with the factory of CelValue instead of the generic Add<T>. A form with classes of the
// application has a source of types, which lists the descriptions that its properties reach, and the declare delegate adds it first;
// a collection of classes is declared with the CelType of its shape and bound with a view, closed over the type of its element.
internal static class RegistrationEmitter
{
    private const string Values = "global::Great.Parts.Cel.Values.";
    private const string CelValue = Values + "CelValue";

    internal static string HintName(int number) => "CelAnonymousData_" + number + ".g.cs";

    // descriptions is the model of the file of descriptions: null for a form that reaches no class.
    internal static string Write(AnonymousShape shape, int number, ClassDescriptionsModel? descriptions)
    {
        PropertyModel[] properties = shape.Properties.Items;
        bool classes = shape.Objects.Length > 0 || shape.Enums.Length > 0;
        var text = new StringBuilder();
        text.Append("// <auto-generated/>\n");

        // The element of a collection may be a reference type that its annotation allows to be null: the text of the type has a ?, which
        // a context without annotations warns about.
        text.Append(HasCollection(properties) ? "#nullable enable annotations\n" : "#nullable disable\n");
        text.Append("file static class CelAnonymousData_").Append(number).Append('\n');
        text.Append("{\n");
        if (classes && descriptions is not null)
        {
            WriteSource(text, shape, number, descriptions, new ObjectIndex(descriptions.Objects));
        }

        text.Append("    [global::System.Runtime.CompilerServices.ModuleInitializer]\n");
        text.Append("    internal static void Register() =>\n");
        text.Append("        global::Great.Parts.Cel.CelAnonymousData.Register(\n");
        WriteExample(text, properties);
        WriteDeclare(text, properties, classes);
        WriteBind(text, properties, new ObjectIndex(descriptions?.Objects ?? default));
        text.Append(");\n");
        text.Append("}\n");
        return text.ToString();
    }

    // The anonymous object of the same type as the one of the call, with the default value of each property.
    private static void WriteExample(StringBuilder text, PropertyModel[] properties)
    {
        text.Append("            new { ");
        for (int index = 0; index < properties.Length; index++)
        {
            text.Append(index == 0 ? string.Empty : ", ")
                .Append(PropertyRules.Identifier(properties[index].Name))
                .Append(" = default(")
                .Append(properties[index].CSharpType)
                .Append(')');
        }

        text.Append(properties.Length == 0 ? "}" : " }").Append(",\n");
    }

    private static void WriteDeclare(StringBuilder text, PropertyModel[] properties, bool classes)
    {
        text.Append("            static builder => ");
        if (properties.Length == 0)
        {
            text.Append("{ }");
        }
        else
        {
            text.Append("builder").Append(classes ? ".AddTypes(Types)" : string.Empty);
            foreach (PropertyModel property in properties)
            {
                text.Append(Declaration(property));
            }
        }

        text.Append(",\n");
    }

    private static void WriteBind(StringBuilder text, PropertyModel[] properties, ObjectIndex objects)
    {
        text.Append("            static (data, bindings) => ");
        if (properties.Length == 0)
        {
            text.Append("{ }");
        }
        else
        {
            text.Append("bindings");
            foreach (PropertyModel property in properties)
            {
                text.Append(".Add(\"").Append(property.Name).Append("\", ").Append(Binding(property, objects)).Append(')');
            }
        }
    }

    private static bool HasCollection(PropertyModel[] properties)
    {
        foreach (PropertyModel property in properties)
        {
            if (property.Collection is not null)
            {
                return true;
            }
        }

        return false;
    }

    // The source of types of the form: the descriptions and the enumerations that its properties reach, in the order of the CEL names.
    // The descriptions are those of the file of descriptions, so one description serves every form that reaches its type.
    private static void WriteSource(StringBuilder text, AnonymousShape shape, int number, ClassDescriptionsModel descriptions, ObjectIndex objects)
    {
        text.Append("    private sealed class TypeSource()\n");
        text.Append("        : ").Append(Values).Append("CelTypeProvider(\n");
        text.Append("            ").Append(Literals.Quote("CelAnonymousData_" + number)).Append(",\n");
        text.Append("            [");
        bool first = true;
        foreach (string name in shape.Objects.Items)
        {
            if (objects.Find(name) is { } type)
            {
                text.Append(first ? string.Empty : ", ").Append(CallSiteNames.TypesClass).Append('.').Append(type.ClassName).Append(".Description");
                first = false;
            }
        }

        text.Append("],\n");
        text.Append("            [");
        first = true;
        foreach (string name in shape.Enums.Items)
        {
            foreach (EnumModel enumeration in descriptions.Enums.Items)
            {
                if (enumeration.CelName == name)
                {
                    text.Append(first ? string.Empty : ", ").Append(CallSiteNames.TypesClass).Append('.').Append(enumeration.FieldName);
                    first = false;
                }
            }
        }

        text.Append("]);\n\n");
        text.Append("    private static readonly TypeSource Types = new();\n\n");
    }

    // The variable of a property: AddVariable<T>, where the library gives the CEL type of T, or the CelType of the shape of a
    // collection of classes.
    private static string Declaration(PropertyModel property) =>
        property.Collection is { } collection
            ? ".AddVariable(\"" + property.Name + "\", " + CelTypeExpressions.Of(CelTypes.Of(collection)) + ")"
            : ".AddVariable<" + property.CSharpType + ">(\"" + property.Name + "\")";

    // The value of a property: the property itself for Add<T>, the factory of CelValue for a row that cannot fail, the view of a collection.
    private static string Binding(PropertyModel property, ObjectIndex objects)
    {
        string access = "data." + PropertyRules.Identifier(property.Name);
        if (property.Collection is { } collection)
        {
            return ValueReader.ForCallSite(objects).Read(collection, new Operand(access));
        }

        return property.Direct == DirectKind.None ? access : Direct(property, access);
    }

    // The row of the type with the same handling of null as the row: a null string, list or map is the null value, and an absent
    // Nullable<> too.
    private static string Direct(PropertyModel property, string access)
    {
        string factory = property.Direct switch
        {
            DirectKind.Bool => "FromBoolean",
            DirectKind.Int => "FromInt64",
            DirectKind.UInt => "FromUInt64",
            DirectKind.Double => "FromDouble",
            DirectKind.String => "FromString",
            DirectKind.CelList => "FromList",
            DirectKind.CelMap => "FromMap",
            _ => "FromString",
        };

        string nullValue = CelValue + ".Null";
        if (property.DirectNullable)
        {
            return access + ".HasValue ? " + CelValue + "." + factory + "(" + access + ".Value) : " + nullValue;
        }

        if (property.Direct == DirectKind.Guid)
        {
            return CelValue + "." + factory + "(" + access + ".ToString(\"D\"))";
        }

        string value = CelValue + "." + factory + "(" + access + ")";
        return property.Direct is DirectKind.String or DirectKind.CelList or DirectKind.CelMap
            ? access + " is null ? " + nullValue + " : " + value
            : value;
    }
}
