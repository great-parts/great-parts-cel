using System;
using System.Collections.Generic;

namespace Great.Parts.Cel.Generator;

// The text of the one file of descriptions of the assembly: the internal class CelCallSiteTypes with the description of each object
// type and enumeration that the properties of the anonymous objects reach, written by the code of the type context (the same
// DescriptionWriter and ContextWriter.WriteEnum), and what the registrations need besides: the static method that converts an element
// of each type and the owner of the error of a null that a type does not allow.
internal static class DescriptionEmitter
{
    private const string Values = "global::Great.Parts.Cel.Values.";
    private const string CelValue = Values + "CelValue";

    internal static string Write(ClassDescriptionsModel model, EquatableArray<AnonymousShape> shapes, bool internalAccess)
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("// Created by the Great.Parts.Cel source generator. Changes to this file are lost.");
        w.Line("#nullable enable");
        w.EmptyLine();
        w.Open("internal static class " + CallSiteNames.TypesClassName);

        // The members are told apart by an empty line.
        bool started = false;
        foreach (EnumModel enumeration in model.Enums.Items)
        {
            Separate(w, ref started);
            ContextWriter.WriteEnum(w, enumeration, "internal");
        }

        var objects = new ObjectIndex(model.Objects);
        foreach (ObjectTypeModel type in model.Objects.Items)
        {
            Separate(w, ref started);
            DescriptionWriter.Write(w, type, objects, ContextWriter.Version, "internal", internalAccess);
        }

        var strict = new HashSet<string>(StringComparer.Ordinal);
        var lenient = new HashSet<string>(StringComparer.Ordinal);
        bool collections = false;
        foreach (AnonymousShape shape in shapes.Items)
        {
            foreach (PropertyModel property in shape.Properties.Items)
            {
                if (property.Collection is not null)
                {
                    collections = true;
                    Leaves(property.Collection, strict, lenient);
                }
            }
        }

        foreach (ObjectTypeModel type in model.Objects.Items)
        {
            if (lenient.Contains(type.CelName))
            {
                Separate(w, ref started);
                WriteConverter(w, type, false);
            }

            if (strict.Contains(type.CelName))
            {
                Separate(w, ref started);
                WriteConverter(w, type, true);
            }
        }

        if (collections)
        {
            Separate(w, ref started);
            WriteOwner(w, internalAccess);
        }

        w.Close();
        return w.ToString();
    }

    private static void Separate(CodeWriter w, ref bool started)
    {
        if (started)
        {
            w.EmptyLine();
        }

        started = true;
    }

    // The object types at the ends of a chain of collections: the types of the elements and of the values that the created code
    // converts, those of a place that does not take null apart from the others.
    private static void Leaves(Shape shape, HashSet<string> strict, HashSet<string> lenient)
    {
        switch (shape)
        {
            case CollectionShape collection:
                Leaves(collection.Element, strict, lenient);
                break;
            case NullableShape nullable:
                Leaves(nullable.Underlying, strict, lenient);
                break;
            case ObjectShape { Kind: not ObjectKind.Message } leaf:
                (CallSiteNames.IsStrict(leaf) ? strict : lenient).Add(leaf.CelName);
                break;
            default:
                break;
        }
    }

    // The method of one type: it pairs the description of the declared type with the instance, so that an instance of a derived class is
    // read by the members of the declared type. A null is the null value, or an error value for a place that does not take null.
    private static void WriteConverter(CodeWriter w, ObjectTypeModel type, bool strict)
    {
        string name = CallSiteNames.Converter(type.ClassName, strict);
        string paired = CelValue + ".FromObject(" + type.ClassName + ".Description, e)";
        if (type.Kind == ObjectKind.Struct)
        {
            w.Line("internal static " + CelValue + " " + name + "(" + type.ClrName + " e) => " + paired + ";");
            return;
        }

        w.Line("internal static " + CelValue + " " + name + "(" + type.ClrName + (strict ? string.Empty : "?") + " e) =>");
        w.Indent();
        w.Line("e is null ? " + (strict ? "Unexpected()" : CelValue + ".Null") + " : " + paired + ";");
        w.Outdent();
    }

    // A null that a type does not allow is an error value of a field of a description, and only a description can make one. The owner is
    // a description of no type: no source lists it, and nothing reads a field of it.
    private static void WriteOwner(CodeWriter w, bool internalAccess)
    {
        string modifiers = DescriptionWriter.Override(internalAccess);
        w.Line("internal static " + CelValue + " Unexpected() => NullOwner.Instance.Error();");
        w.EmptyLine();
        w.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"Great.Parts.Cel.Generator\", " + Literals.Quote(ContextWriter.Version) + ")]");
        w.Open("private sealed class NullOwner : " + Values + "CelObjectType<object>");
        w.Line("internal static readonly NullOwner Instance = new();");
        w.EmptyLine();
        w.Line("private NullOwner()");
        w.Indent();
        w.Line(": base(\"CelCallSite\", [new(0, \"value\", global::Great.Parts.Cel.Types.CelType.Dyn)])");
        w.Outdent();
        w.Line("{");
        w.Line("}");
        w.EmptyLine();
        w.Line("internal " + CelValue + " Error() => FieldError(0, global::Great.Parts.Cel.Diagnostics.CelErrorCode.UnexpectedNull, null);");
        w.EmptyLine();
        w.Line(modifiers + CelValue + " GetField(in object instance, int number) => " + CelValue + ".Null;");
        w.EmptyLine();
        w.Line(modifiers + "bool HasField(object instance, int number) => false;");
        w.Close();
    }
}
