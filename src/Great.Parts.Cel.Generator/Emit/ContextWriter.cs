using System.Collections.Generic;

namespace Great.Parts.Cel.Generator;

// The file of one type context: the header, the namespace and the containing types, and the partial class of the context with the
// enumerations, Default, the private constructor and the descriptions ("The file" of the page of the created code).
internal static class ContextWriter
{
    private const string Values = "global::Great.Parts.Cel.Values.";

    // The version of the generator assembly, the only text of the file that changes with a release of the library.
    private static readonly string Version = typeof(ContextWriter).Assembly.GetName().Version?.ToString() ?? "0.0.0.0";

    internal static string Write(ContextModel model)
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("// Created by the Great.Parts.Cel source generator. Changes to this file are lost.");
        w.Line("#nullable enable");
        w.EmptyLine();

        int blocks = 0;
        if (model.Namespace.Length > 0)
        {
            w.Open("namespace " + Literals.QualifiedName(model.Namespace));
            blocks++;
        }

        // A containing type is declared partial with its keyword and nothing else: the other parts state the modifiers.
        foreach (ContainingTypeModel container in model.ContainingTypes.Items)
        {
            w.Open("partial " + container.Keyword + " " + Literals.Identifier(container.Name));
            blocks++;
        }

        WriteContext(w, model);
        for (int block = 0; block < blocks; block++)
        {
            w.Close();
        }

        return w.ToString();
    }

    private static void WriteContext(CodeWriter w, ContextModel model)
    {
        string name = Literals.Identifier(model.Name);
        w.Open("partial class " + name);

        // The enumerations come first and Default after all of them: the initializers of one part run in the order of the text, and
        // the constructor reads the enumeration fields.
        foreach (EnumModel enumeration in model.Enums.Items)
        {
            WriteEnum(w, enumeration);
            w.EmptyLine();
        }

        w.Line("/// <summary>The only instance of the context.</summary>");
        w.Line("public static " + name + " Default { get; } = new " + name + "();");
        w.EmptyLine();
        WriteConstructor(w, model, name);

        var objects = new ObjectIndex(model.ObjectTypes);
        foreach (ObjectTypeModel type in model.ObjectTypes.Items)
        {
            w.EmptyLine();
            DescriptionWriter.Write(w, type, objects, Version);
        }

        w.Close();
    }

    private static void WriteEnum(CodeWriter w, EnumModel enumeration)
    {
        var constants = new List<string>();
        foreach (EnumConstantModel constant in enumeration.Constants.Items)
        {
            constants.Add("new(" + Literals.Quote(constant.Name) + ", " + Literals.Long(constant.Value) + ")");
        }

        w.Line("private static readonly " + Values + "CelEnumType " + enumeration.FieldName + " = new(");
        w.Indent();
        w.Line(Literals.Quote(enumeration.CelName) + ",");
        w.Line("[" + string.Join(", ", constants) + "]);");
        w.Outdent();
    }

    private static void WriteConstructor(CodeWriter w, ContextModel model, string name)
    {
        var types = new List<string>();
        foreach (ObjectTypeModel type in model.ObjectTypes.Items)
        {
            types.Add(type.ClassName + ".Description");
        }

        var enums = new List<string>();
        foreach (EnumModel enumeration in model.Enums.Items)
        {
            enums.Add(enumeration.FieldName);
        }

        w.Line("private " + name + "()");
        w.Indent();
        w.Line(": base(");
        w.Indent();
        w.Line(Literals.Quote(model.SourceName) + ",");
        w.Line("[" + string.Join(", ", types) + "],");
        w.Line("[" + string.Join(", ", enums) + "])");
        w.Outdent();
        w.Outdent();
        w.Line("{");
        w.Line("}");
    }
}
