using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace Great.Parts.Cel.Generator.Tests.Examples.Pipeline;

// The form of the created file of the smallest context (two types and an enumeration), which the generator output page gives
// as its reference: the header, the namespace block, the partial class with Default and a private constructor, the base
// call, the descriptions with their fields in the order of the CEL names. The examples fix what an application and the snapshots
// rely on and leave the layout to the snapshots: the form is a contract of the minor versions, not every space of it.
public sealed class CreatedFileTests
{
    private const string Smallest = SnapshotContexts.Smallest;

    [Fact]
    [Trait("Requirement", "S-2")]
    [Trait("Requirement", "F-2")]
    public void CreatedFile_HasTheHeaderTheNamespaceAndTheContext()
    {
        GeneratorDriverRunResult result = GeneratorExample.Run(GeneratorExample.Compile(Smallest));

        string text = GeneratorExample.CreatedText(result);
        string[] lines = text.Split('\n');
        Assert.Empty(GeneratorExample.Reported(result));
        Assert.Equal("Acme.Sales.OrderContext.g.cs", Assert.Single(result.Results).GeneratedSources.Single().HintName);
        Assert.Equal("// <auto-generated/>", lines[0]);
        Assert.Equal("// Created by the Great.Parts.Cel source generator. Changes to this file are lost.", lines[1]);
        Assert.Equal("#nullable enable", lines[2]);
        Assert.Contains("\nnamespace Acme.Sales\n{\n", text, System.StringComparison.Ordinal);
        Assert.Contains("partial class OrderContext\n", text, System.StringComparison.Ordinal);
        Assert.Contains("public static OrderContext Default { get; } = new OrderContext();", text, System.StringComparison.Ordinal);
        Assert.Contains("private OrderContext()", text, System.StringComparison.Ordinal);
        Assert.Contains("\"OrderContext\",", text, System.StringComparison.Ordinal);
        Assert.EndsWith("}\n", text, System.StringComparison.Ordinal);
        Assert.DoesNotContain("\r", text, System.StringComparison.Ordinal);
    }

    // What the file does not have: a using directive (every name is written with global::), a pragma, a suppression, and the text
    // of the application's names in a place where it could collide with the generator's.
    [Fact]
    [Trait("Requirement", "S-2")]
    public void CreatedFile_HasNoUsingNoPragmaAndNoSuppression()
    {
        string text = GeneratorExample.CreatedText(GeneratorExample.Run(GeneratorExample.Compile(Smallest)));

        Assert.DoesNotContain("using ", text, System.StringComparison.Ordinal);
        Assert.DoesNotContain("#pragma", text, System.StringComparison.Ordinal);
        Assert.DoesNotContain("SuppressMessage", text, System.StringComparison.Ordinal);
        Assert.DoesNotContain("Environment.NewLine", text, System.StringComparison.Ordinal);
        Assert.Contains("[global::System.CodeDom.Compiler.GeneratedCode(\"Great.Parts.Cel.Generator\", \"", text, System.StringComparison.Ordinal);
    }

    // The enumerations are static fields that the constructor of the context takes, so they are initialized before Default
    // creates the context: the order of the declarations in the file is the order of the initialization ("Initialization order" of
    // the page of the created code). The names of the fields are not part of the contract, so the example looks for the declaration.
    [Fact]
    [Trait("Requirement", "S-2")]
    [Trait("Requirement", "F-2")]
    public void EnumerationFields_AreDeclaredBeforeDefault()
    {
        string text = GeneratorExample.CreatedText(GeneratorExample.Run(GeneratorExample.Compile(Smallest)));

        int enumeration = text.IndexOf("static readonly global::Great.Parts.Cel.Values.CelEnumType ", System.StringComparison.Ordinal);
        int created = text.IndexOf("public static OrderContext Default", System.StringComparison.Ordinal);
        Assert.True(enumeration >= 0 && created >= 0 && enumeration < created, "the field of the enumeration is declared after Default");
        Assert.Contains("\"Acme.Sales.Status\"", text, System.StringComparison.Ordinal);
        Assert.Contains("new(\"Draft\", 0L), new(\"Approved\", 1L)", text, System.StringComparison.Ordinal);
    }

    // The fields of a description in the order of their CEL names, ordinal, numbered by position; the types by the rows of the
    // type mapping: a string that is not null is string, a list of objects names the object type, an enumeration is int.
    [Fact]
    [Trait("Requirement", "S-2")]
    [Trait("Requirement", "F-2")]
    public void Fields_AreInTheOrderOfTheirNamesWithTheirCelTypes()
    {
        string text = GeneratorExample.CreatedText(GeneratorExample.Run(GeneratorExample.Compile(Smallest)));

        string[] expected =
        [
            "new(0, \"currency\", global::Great.Parts.Cel.Types.CelType.String)",
            "new(1, \"lines\", global::Great.Parts.Cel.Types.CelType.ListOf(global::Great.Parts.Cel.Types.CelType.ObjectNamed(\"Acme.Sales.OrderLine\")))",
            "new(2, \"status\", global::Great.Parts.Cel.Types.CelType.Int)",
        ];
        int position = -1;
        foreach (string field in expected)
        {
            int at = text.IndexOf(field, System.StringComparison.Ordinal);
            Assert.True(at > position, "missing or out of order: " + field);
            position = at;
        }

        Assert.Contains("\"Acme.Sales.Order\"", text, System.StringComparison.Ordinal);
        Assert.Contains("typeof(global::Acme.Sales.Order)", text, System.StringComparison.Ordinal);
        Assert.Contains("\"Acme.Sales.OrderLine\"", text, System.StringComparison.Ordinal);
    }

    // A project that has the nullable context off: a string without an annotation is read as nullable, so its CEL type is the
    // wrapper; the file does not depend on the project for anything else.
    [Fact]
    [Trait("Requirement", "F-2")]
    public void NullableContextOff_GivesTheWrapperOfString()
    {
        string text = GeneratorExample.CreatedText(
            GeneratorExample.Run(GeneratorExample.Compile(Smallest, nullable: NullableContextOptions.Disable)));

        Assert.Contains("new(0, \"currency\", global::Great.Parts.Cel.Types.CelType.WrapperOf(global::Great.Parts.Cel.Types.CelType.String))", text, System.StringComparison.Ordinal);
    }

    // The nested classes and fields carry a prefix, so a type of the application whose CEL name is one identifier — a type of the
    // global namespace named Default, Create, SourceName, ObjectTypes or EnumTypes, or named as the context itself — does not collide
    // with a member of the context or of CelTypeProvider: the context and the file compile, with no error and no warning at the file.
    [Fact]
    [Trait("Requirement", "S-2")]
    [Trait("Requirement", "F-2")]
    public void TypesNamedLikeMembersOfTheContext_DoNotCollide()
    {
        const string Source = """
            using Great.Parts.Cel.Values;
            public class Default { public long V { get; set; } public Mode Mode { get; set; } }
            public class Create { public long V { get; set; } }
            public class SourceName { public long V { get; set; } }
            public class ObjectTypes { public long V { get; set; } }
            public class EnumTypes { public long V { get; set; } }
            public class OrderContext { public long V { get; set; } }
            public enum Mode { A }
            namespace Acme
            {
                [CelObject(typeof(global::Default))]
                [CelObject(typeof(global::Create))]
                [CelObject(typeof(global::SourceName))]
                [CelObject(typeof(global::ObjectTypes))]
                [CelObject(typeof(global::EnumTypes))]
                [CelObject(typeof(global::OrderContext))]
                public partial class OrderContext : CelTypeContext { }
            }
            """;

        CSharpCompilation compilation = GeneratorExample.Compile(Source);
        GeneratorDriverRunResult result = GeneratorExample.Run(compilation);

        Assert.Empty(GeneratorExample.Reported(result));
        Assert.Empty(compilation.AddSyntaxTrees(result.GeneratedTrees).GetDiagnostics().Where(diagnostic => diagnostic.Severity != DiagnosticSeverity.Hidden && diagnostic.Severity != DiagnosticSeverity.Info));
    }

    // The hint name is the full metadata name of the context, nested types joined by `+`; a context of the global namespace has
    // no namespace block.
    [Fact]
    [Trait("Requirement", "S-2")]
    public void HintName_IsTheMetadataNameOfTheContext()
    {
        const string Source = """
            using Great.Parts.Cel.Values;
            namespace Acme.Sales
            {
                public partial class Outer
                {
                    [CelObject(typeof(Thing))]
                    public partial class OrderContext : CelTypeContext { }
                }
                public class Thing { public long V { get; set; } }
            }
            [CelObject(typeof(Acme.Sales.Thing))]
            public partial class GlobalContext : CelTypeContext { }
            """;

        GeneratorDriverRunResult result = GeneratorExample.Run(GeneratorExample.Compile(Source));

        string[] hints = [.. result.Results.Single().GeneratedSources.Select(source => source.HintName).Order(System.StringComparer.Ordinal)];
        Assert.Equal(["Acme.Sales.Outer+OrderContext.g.cs", "GlobalContext.g.cs"], hints);
        string global = result.GeneratedTrees.Single(tree => tree.FilePath.EndsWith("GlobalContext.g.cs", System.StringComparison.Ordinal)).GetText().ToString();
        Assert.DoesNotContain("namespace ", global, System.StringComparison.Ordinal);
        string nested = result.GeneratedTrees.Single(tree => tree.FilePath.EndsWith("Outer+OrderContext.g.cs", System.StringComparison.Ordinal)).GetText().ToString();
        Assert.Contains("partial class Outer", nested, System.StringComparison.Ordinal);
    }

    // The created code is not a source of warnings: with the compiler's own diagnostics at their default levels the compilation
    // of the application and the file reports nothing at the created file, for the C# versions from 12 on and for a project with
    // or without the nullable context (a warning that the created file gets is a defect of the generator).
    [Theory]
    [Trait("Requirement", "S-2")]
    [Trait("Requirement", "F-2")]
    [InlineData(LanguageVersion.CSharp12, NullableContextOptions.Enable)]
    [InlineData(LanguageVersion.CSharp12, NullableContextOptions.Disable)]
    [InlineData(LanguageVersion.Latest, NullableContextOptions.Enable)]
    [InlineData(LanguageVersion.Latest, NullableContextOptions.Warnings)]
    public void CreatedCode_CompilesWithoutDiagnostics(LanguageVersion version, NullableContextOptions nullable)
    {
        CSharpCompilation compilation = GeneratorExample.Compile(Smallest, version, nullable);
        GeneratorDriverRunResult result = GeneratorExample.Run(compilation);

        CSharpCompilation withCreated = compilation.AddSyntaxTrees(result.GeneratedTrees);

        Assert.Empty(withCreated.GetDiagnostics().Where(diagnostic => diagnostic.Location.SourceTree is { FilePath: var path } && path.EndsWith(".g.cs", System.StringComparison.Ordinal)));
        Assert.Empty(withCreated.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));
    }
}
