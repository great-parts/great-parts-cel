using System;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace Great.Parts.Cel.Generator.Tests.Examples.CallSites;

// The generator of call sites of CelExpression.Evaluate (diagnostics GPCEL010 and GPCEL011). One created file per distinct
// anonymous type (names, types and order of the properties), found by the symbol of the method; nothing for a listed dictionary;
// a warning where the static type hides the data; an error for a property the simple entry cannot read. The compilation is the
// one of GeneratorExample. A class of the application in a property is read by the generator (ClassCallSiteTests), so it is no
// case of GPCEL011 here.
[Trait("Requirement", "U-7")]
public sealed class CallSiteTests
{
    private const string Head = "using System.Collections.Generic;\nusing Great.Parts.Cel;\nnamespace Acme;\n";

    [Fact]
    public void OneAnonymousTypeAtTwoCalls_IsOneFileAndOneRegistration()
    {
        Outcome outcome = Run(Body(
            "CelExpression.Evaluate<long>(\"(x + 2) / 3\", new { x = 40L });\n"
            + "var d = new { x = 5L };\n"
            + "CelExpression.Evaluate<long>(\"x * 2\", d);\n"));

        Assert.Empty(outcome.Reported);
        Assert.Equal(["CelAnonymousData_1.g.cs"], outcome.HintNames);
        Assert.Empty(outcome.CompilerErrors);
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable disable
            file static class CelAnonymousData_1
            {
                [global::System.Runtime.CompilerServices.ModuleInitializer]
                internal static void Register() =>
                    global::Great.Parts.Cel.CelAnonymousData.Register(
                        new { x = default(long) },
                        static builder => builder.AddVariable<long>("x"),
                        static (data, bindings) => bindings.Add("x", global::Great.Parts.Cel.Values.CelValue.FromInt64(data.x)));
            }

            """.Replace("\r\n", "\n", StringComparison.Ordinal),
            outcome.Texts[0]);
    }

    // Another set or another order of properties is another type of C#, so another file.
    [Fact]
    public void OtherPropertiesOrOrder_IsAnotherFile()
    {
        Outcome outcome = Run(Body(
            "CelExpression.Evaluate<long>(\"x\", new { x = 1L });\n"
            + "CelExpression.Evaluate<long>(\"x\", new { x = 1L, name = \"a\" });\n"
            + "CelExpression.Evaluate<long>(\"x\", new { name = \"a\", x = 1L });\n"));

        Assert.Equal(["CelAnonymousData_1.g.cs", "CelAnonymousData_2.g.cs", "CelAnonymousData_3.g.cs"], outcome.HintNames);
        Assert.Empty(outcome.CompilerErrors);
    }

    // The call is found by the symbol: a full name, using static and an alias; a method Evaluate of another type is not a call site.
    [Fact]
    public void CallIsFoundByTheSymbol()
    {
        const string Source = "using static Great.Parts.Cel.CelExpression;\nusing E = Great.Parts.Cel.CelExpression;\nnamespace Acme;\n"
            + "class Other { public static long Evaluate<T>(string s, object o) => 0; }\n"
            + "class C\n{\n    void M()\n    {\n"
            + "        Great.Parts.Cel.CelExpression.Evaluate<long>(\"a\", new { a = 1L });\n"
            + "        Evaluate<long>(\"b\", new { b = 1L });\n"
            + "        E.Evaluate<long>(\"c\", new { c = 1L });\n"
            + "        Other.Evaluate<long>(\"d\", new { d = 1L });\n"
            + "    }\n}\n";

        Outcome outcome = Run(Source);

        Assert.Equal(3, outcome.HintNames.Length);
        Assert.DoesNotContain(outcome.Texts, text => text.Contains("\"d\"", StringComparison.Ordinal));
    }

    [Theory]
    [InlineData("new Dictionary<string, long> { [\"a\"] = 1 }")]
    [InlineData("(IReadOnlyDictionary<string, object?>)new Dictionary<string, object?>()")]
    public void ListedDictionary_IsNothing(string data)
    {
        Outcome outcome = Run(Body("CelExpression.Evaluate<long>(\"1\", " + data + ");\n"));

        Assert.Empty(outcome.Reported);
        Assert.Empty(outcome.HintNames);
    }

    [Theory]
    [InlineData("object o = new { x = 1L };\nCelExpression.Evaluate<long>(\"x\", o);\n", "object", "o")]
    [InlineData("CelExpression.Evaluate<long>(\"1\", new Order());\n", "Acme.Order", "new Order()")]
    [InlineData("CelExpression.Evaluate<long>(\"1\", new Dictionary<int, long>());\n", "System.Collections.Generic.Dictionary<int, long>", "new Dictionary<int, long>()")]
    public void HiddenOrUnreadableStaticType_IsGPCEL010AtTheArgument(string statements, string shown, string place)
    {
        Outcome outcome = Run(Body(statements));

        Diagnostic warning = Assert.Single(outcome.Reported);
        Assert.Equal("GPCEL010", warning.Id);
        Assert.Equal(DiagnosticSeverity.Warning, warning.Severity);
        Assert.StartsWith("The static type '" + shown + "' of the data argument of CelExpression.Evaluate", warning.GetMessage(), StringComparison.Ordinal);
        Assert.Equal(place, Place(warning));
        Assert.Empty(outcome.HintNames);
    }

    [Fact]
    public void GenericWrapper_IsGPCEL010()
    {
        Outcome outcome = Run(Head + "public sealed class Order { }\nclass C\n{\n"
            + "    long Wrap<TData>(TData d) where TData : notnull => CelExpression.Evaluate<long>(\"1\", d);\n}\n");

        Diagnostic warning = Assert.Single(outcome.Reported);
        Assert.Equal("GPCEL010", warning.Id);
        Assert.Contains("'TData'", warning.GetMessage(), StringComparison.Ordinal);
        Assert.Equal("d", Place(warning));
    }

    [Theory]
    [InlineData("new { a = new { b = 1 } }", "a", "<anonymous type: int b>")]
    [InlineData("new { o = (object)1 }", "o", "object")]
    [InlineData("new { s = new HashSet<long>() }", "s", "System.Collections.Generic.HashSet<long>")]
    [InlineData("new { loop = 1L }", "loop", "long")]
    public void PropertyOutsideTheList_IsGPCEL011AtTheProperty(string data, string property, string shown)
    {
        Outcome outcome = Run(Body("CelExpression.Evaluate<long>(\"1\", " + data + ");\n"));

        Diagnostic error = Assert.Single(outcome.Reported);
        Assert.Equal("GPCEL011", error.Id);
        Assert.Equal(DiagnosticSeverity.Error, error.Severity);
        Assert.StartsWith("Property '" + property + "' of the anonymous data has type '" + shown + "'", error.GetMessage(), StringComparison.Ordinal);
        Assert.StartsWith(property, Place(error), StringComparison.Ordinal);
        Assert.Empty(outcome.HintNames);
    }

    [Fact]
    public void PropertyOfAnInaccessibleType_IsGPCEL011()
    {
        Outcome outcome = Run(Head + "class Outer\n{\n    private sealed class Hidden { }\n"
            + "    void M() { CelExpression.Evaluate<long>(\"1\", new { h = new Hidden() }); }\n}\n");

        Diagnostic error = Assert.Single(outcome.Reported);
        Assert.Equal("GPCEL011", error.Id);
        Assert.Contains("not accessible", error.GetMessage(), StringComparison.Ordinal);
    }

    // The properties of the list: scalars, nullable values, bytes, time, lists and dictionaries of the list of the simple entry.
    [Fact]
    public void PropertiesOfTheList_AreOneFileWithoutErrors()
    {
        Outcome outcome = Run(Body(
            "CelExpression.Evaluate<bool>(\"true\", new { b = true, i = 1, l = 2L, u = 3u, d = 1.5, s = \"x\", g = System.Guid.Empty, "
            + "n = (long?)null, bytes = new byte[0], t = System.DateTimeOffset.UnixEpoch, span = System.TimeSpan.Zero, "
            + "ids = new List<long>(), names = new string[0], map = new Dictionary<string, double>(), any = new List<object>() });\n"));

        Assert.Empty(outcome.Reported);
        Assert.Single(outcome.HintNames);
        Assert.Empty(outcome.CompilerErrors);
    }

    private static string Body(string statements) =>
        Head + "public sealed class Order { }\nclass C\n{\n    void M()\n    {\n" + statements + "    }\n}\n";

    private static string Place(Diagnostic diagnostic) =>
        diagnostic.Location.SourceTree!.GetText().ToString(diagnostic.Location.SourceSpan);

    private static Outcome Run(string source)
    {
        CSharpCompilation compilation = GeneratorExample.Compile(source, LanguageVersion.CSharp12);
        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            [new CelAnonymousDataGenerator().AsSourceGenerator()],
            parseOptions: new CSharpParseOptions(LanguageVersion.CSharp12));
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation output, out _);
        GeneratorDriverRunResult result = driver.GetRunResult();
        GeneratedSourceResult[] sources = [.. result.Results.SelectMany(run => run.GeneratedSources).OrderBy(source => source.HintName, StringComparer.Ordinal)];

        return new Outcome(
            [.. result.Diagnostics.Where(diagnostic => diagnostic.Id.StartsWith("GPCEL", StringComparison.Ordinal))],
            [.. sources.Select(source => source.HintName)],
            [.. sources.Select(source => source.SourceText.ToString().Replace("\r\n", "\n", StringComparison.Ordinal))],
            [.. output.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)]);
    }

    private sealed record Outcome(ImmutableArray<Diagnostic> Reported, string[] HintNames, string[] Texts, ImmutableArray<Diagnostic> CompilerErrors);
}
