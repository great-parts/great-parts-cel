    // Two types of one CEL name reached by two properties: the second is reported at its property and left out.
    [Fact]
    public void TwoTypesOfOneCelName_AreGPCEL004AtTheSecondProperty()
    {
        const string Types = "public sealed class A_B { }\n"
            + "public sealed class Box<T> { public T? Value { get; set; } }\n"
            + "public sealed class Box_Acme_A_B { public long X { get; set; } }\n";
        Outcome outcome = Run(Source(Types, "CelExpression.Evaluate<bool>(\"true\", new { a = new Box<A_B>(), b = new Box_Acme_A_B() });\n"));

        Diagnostic error = Assert.Single(outcome.Reported, diagnostic => diagnostic.Id == "GPCEL004");
        Assert.Equal(DiagnosticSeverity.Error, error.Severity);
        Assert.Equal(
            "Types 'Acme.Box<Acme.A_B>' and 'Acme.Box_Acme_A_B' in type context 'CelExpression.Evaluate' both map to the CEL type name 'Acme.Box_Acme_A_B'",
            error.Message());
        Assert.StartsWith("b", Place(error), StringComparison.Ordinal);
    }

