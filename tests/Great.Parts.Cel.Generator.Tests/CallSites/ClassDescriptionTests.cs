    private static string Source(string types, string statements) => Head + types + Call + statements + "    }\n}\n";

    [Fact]
    public void ClassAndCollectionOfClasses_AreTheSnapshotOfBothFiles()
    {
        Outcome outcome = Run(Source(Line, "CelExpression.Evaluate<bool>(\"true\", new { n = 1L, line = new Line(), lines = new List<Line>() });\n"));

        Assert.Empty(outcome.Reported);
        Assert.Empty(outcome.CompilerErrors);
        Assert.Equal(["CelAnonymousData_1.g.cs", "CelCallSiteTypes.g.cs"], outcome.HintNames);
        Assert.Equal(Registration, outcome.Texts[0]);
        Assert.Equal(Descriptions, SnapshotText.Normalize(outcome.Texts[1]));
    }

    // Two forms that reach one class share its description; each form lists only the types its properties reach.
    [Fact]
    public void TwoForms_ShareOneDescription_AndListOnlyTheTypesTheyReach()
    {
        const string Types = Line
            + "public sealed class Order { public Line[] Lines { get; set; } = []; }\n"
            + "public sealed class Other { public long V { get; set; } }\n";
        Outcome outcome = Run(Source(
            Types,
            "CelExpression.Evaluate<bool>(\"true\", new { o = new Order() });\n"
            + "CelExpression.Evaluate<bool>(\"true\", new { x = new Other(), n = 1L });\n"
            + "CelExpression.Evaluate<bool>(\"true\", new { n = 1L });\n"));

        Assert.Empty(outcome.Reported);
        Assert.Empty(outcome.CompilerErrors);
        Assert.Equal(["CelAnonymousData_1.g.cs", "CelAnonymousData_2.g.cs", "CelAnonymousData_3.g.cs", "CelCallSiteTypes.g.cs"], outcome.HintNames);
        Assert.Contains("[global::CelCallSiteTypes.Type_Acme_Line.Description, global::CelCallSiteTypes.Type_Acme_Order.Description]", outcome.Texts[0], StringComparison.Ordinal);
        Assert.Contains("[global::CelCallSiteTypes.Type_Acme_Other.Description]", outcome.Texts[1], StringComparison.Ordinal);
        Assert.DoesNotContain("Type_Acme_Order", outcome.Texts[1], StringComparison.Ordinal);
        Assert.DoesNotContain("TypeSource", outcome.Texts[2], StringComparison.Ordinal);
        Assert.Equal(1, Count(outcome.Texts[3], "internal sealed class Type_Acme_Line "));
        Assert.Equal(1, Count(outcome.Texts[3], "internal sealed class Type_Acme_Order "));
        Assert.Equal(1, Count(outcome.Texts[3], "internal sealed class Type_Acme_Other "));
    }

    // The converter of an element is one static method for each type and place: a class that its annotation allows to be null has the
    // method that reads null as the null value, one that does not has the method that reads it as an error, a structure has no null.
    [Fact]
    public void ConvertersOfTheElements_AreOneMethodForEachTypeAndKindOfPlace()
    {
        Outcome outcome = Run(Source(
            Line + Point,
            "CelExpression.Evaluate<bool>(\"true\", new { a = new List<Line?>(), b = new List<Line>(), c = new List<Point>(), d = new Line[0], e = new Dictionary<string, Line>() });\n"));

        Assert.Empty(outcome.Reported);
        Assert.Empty(outcome.CompilerErrors);
        string registration = outcome.Texts[0];
        string descriptions = outcome.Texts[1];
        Assert.Equal(3, Count(registration, "CelCallSiteTypes.ConvertNotNull_Acme_Line"));
        Assert.Equal(1, Count(registration, "CelCallSiteTypes.Convert_Acme_Line"));
        Assert.Equal(1, Count(registration, "CelCallSiteTypes.Convert_Acme_Point"));
        Assert.Equal(1, Count(descriptions, "ConvertNotNull_Acme_Line(global::Acme.Line e) =>"));
        Assert.Equal(1, Count(descriptions, "Convert_Acme_Line(global::Acme.Line? e) =>"));
        Assert.Equal(1, Count(descriptions, "Convert_Acme_Point(global::Acme.Point e) =>"));
    }

    // The converter of an element follows the place rule of a member of a context: a sealed class and a structure are bare through the
    // method Placed of their description, a class that is not sealed is bare when the instance is of exactly that class and paired
    // otherwise, and an abstract class and an interface are always paired and have no such method.
    [Fact]
    public void ConvertersOfTheElements_FollowThePlaceRule()
    {
        const string Types = "public interface IShape { double Area { get; } }\n"
            + "public abstract class Base { public string Name { get; set; } = \"\"; }\n"
            + "public class Plain { public long V { get; set; } }\n";
        Outcome outcome = Run(Source(
            Line + Point + Types,
            "CelExpression.Evaluate<bool>(\"true\", new { lines = new List<Line>(), points = new List<Point>(), plains = new List<Plain>(), bases = new Base[0], shapes = new List<IShape>() });\n"));

        Assert.Empty(outcome.Reported);
        Assert.Empty(outcome.CompilerErrors);
        string descriptions = outcome.Texts[1];
        Assert.Equal(3, Count(descriptions, " Placed("));
        string[] expected =
        [
            "Placed(global::Acme.Line e) => FromInstance(e);",
            "Placed(global::Acme.Point e) => FromInstance((object)e);",
            "e.GetType() == typeof(global::Acme.Plain) ? FromInstance(e) : global::Great.Parts.Cel.Values.CelValue.FromObject(Description, e);",
            "e is null ? Unexpected() : Type_Acme_Line.Placed(e);",
            "Convert_Acme_Point(global::Acme.Point e) => Type_Acme_Point.Placed(e);",
            "e is null ? Unexpected() : Type_Acme_Plain.Placed(e);",
            "e is null ? Unexpected() : global::Great.Parts.Cel.Values.CelValue.FromObject(Type_Acme_Base.Description, e);",
            "e is null ? Unexpected() : global::Great.Parts.Cel.Values.CelValue.FromObject(Type_Acme_IShape.Description, e);",
        ];
        foreach (string text in expected)
        {
            Assert.Contains(text, descriptions, StringComparison.Ordinal);
        }
    }

