    // The classes N0 -> N1 -> ... -> N(count - 1): the property of one reaches the next, the last has a scalar.
    private static string Chain(string prefix, int count)
    {
        var source = new StringBuilder();
        for (int index = 0; index < count; index++)
        {
            source.Append("public sealed class ").Append(prefix).Append(index).Append(" { ");
            source.Append(index == count - 1 ? "public long V { get; set; }" : "public " + prefix + (index + 1) + "? Next { get; set; }");
            source.Append(" }\n");
        }

        return source.ToString();
    }

    private static int Count(string text, string part)
    {
        int count = 0;
        for (int index = text.IndexOf(part, StringComparison.Ordinal); index >= 0; index = text.IndexOf(part, index + part.Length, StringComparison.Ordinal))
        {
            count++;
        }

        return count;
    }
