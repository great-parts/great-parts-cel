using System.Collections.Generic;
using System.Threading.Tasks;
using Great.Parts.Cel.Eng.Analyzers;
using Great.Parts.Cel.Eng.Tests.Support;
using Xunit;

namespace Great.Parts.Cel.Eng.Tests.Analyzers;

[Trait("Requirement", "system-S-3")]
public sealed class Arch001Tests
{
    private const string First = """
        using Lib.B;

        namespace Lib.A;

        public static class First
        {
            public static int Value => Second.Value;
        }
        """;

    private const string SecondToFirst = """
        using Lib.A;

        namespace Lib.B;

        public static class Second
        {
            public static int Value => 1;

            public static int Other => First.Value;
        }
        """;

    private const string SecondLeaf = """
        namespace Lib.B;

        public static class Second
        {
            public static int Value => 1;
        }
        """;

    private const string GeneratedBack = """
        using Lib.A;

        namespace Lib.B;

        public static class Back
        {
            public static int Value => First.Value;
        }
        """;

    [Fact]
    public async Task CycleOfTwoNamespaces_IsReportedAtEachEdge()
    {
        IReadOnlyList<AnalyzerFinding> findings = await RunAsync(
            new RepositoryFile("src/Lib/A/First.cs", First),
            new RepositoryFile("src/Lib/B/Second.cs", SecondToFirst));

        FindingAssert.Exactly(
            findings,
            FindingAssert.Error("ARCH001", "src/Lib/A/First.cs", 7, 32, "namespace cycle Lib.A -> Lib.B -> Lib.A; other edge: src/Lib/B/Second.cs(9,32)"),
            FindingAssert.Error("ARCH001", "src/Lib/B/Second.cs", 9, 32, "namespace cycle Lib.B -> Lib.A -> Lib.B; other edge: src/Lib/A/First.cs(7,32)"));
    }

    [Fact]
    public async Task CycleOfThreeNamespaces_IsReportedAtEachEdge()
    {
        IReadOnlyList<AnalyzerFinding> findings = await RunAsync(
            new RepositoryFile("src/Lib/A/First.cs", First),
            new RepositoryFile("src/Lib/B/Second.cs", """
                using Lib.C;

                namespace Lib.B;

                public static class Second
                {
                    public static int Value => Third.Value;
                }
                """),
            new RepositoryFile("src/Lib/C/Third.cs", """
                using Lib.A;

                namespace Lib.C;

                public static class Third
                {
                    public static int Value => First.Value;
                }
                """));

        FindingAssert.Exactly(
            findings,
            FindingAssert.Error("ARCH001", "src/Lib/A/First.cs", 7, 32, "namespace cycle Lib.A -> Lib.B -> Lib.C -> Lib.A; other edge: src/Lib/B/Second.cs(7,32)"),
            FindingAssert.Error("ARCH001", "src/Lib/B/Second.cs", 7, 32, "namespace cycle Lib.B -> Lib.C -> Lib.A -> Lib.B; other edge: src/Lib/C/Third.cs(7,32)"),
            FindingAssert.Error("ARCH001", "src/Lib/C/Third.cs", 7, 32, "namespace cycle Lib.C -> Lib.A -> Lib.B -> Lib.C; other edge: src/Lib/A/First.cs(7,32)"));
    }

    [Fact]
    public async Task ReferencesInOneDirection_AreNotReported()
    {
        IReadOnlyList<AnalyzerFinding> findings = await RunAsync(
            new RepositoryFile("src/Lib/A/First.cs", First),
            new RepositoryFile("src/Lib/B/Second.cs", SecondLeaf));

        FindingAssert.None(findings);
    }

    [Fact]
    public async Task BackReferenceInDocumentation_IsNotCounted()
    {
        IReadOnlyList<AnalyzerFinding> findings = await RunAsync(
            new RepositoryFile("src/Lib/A/First.cs", First),
            new RepositoryFile("src/Lib/B/Second.cs", """
                using Lib.A;

                namespace Lib.B;

                /// <summary>A leaf; <see cref="First"/> reads it.</summary>
                /// <seealso cref="Lib.A.First.Value"/>
                public static class Second
                {
                    /// <summary>Read by <see cref="First.Value"/>.</summary>
                    public static int Value => 1;
                }
                """));

        FindingAssert.None(findings);
    }

    [Fact]
    public async Task BackReferenceInFileWithGeneratedMarker_IsNotCounted()
    {
        IReadOnlyList<AnalyzerFinding> findings = await RunAsync(
            new RepositoryFile("src/Lib/A/First.cs", First),
            new RepositoryFile("src/Lib/B/Second.cs", SecondLeaf),
            new RepositoryFile("src/Lib/B/Back.cs", "// <auto-generated/>\n" + GeneratedBack));

        FindingAssert.None(findings);
    }

    [Fact]
    public async Task BackReferenceInFileWithGeneratedName_IsNotCounted()
    {
        IReadOnlyList<AnalyzerFinding> findings = await RunAsync(
            new RepositoryFile("src/Lib/A/First.cs", First),
            new RepositoryFile("src/Lib/B/Second.cs", SecondLeaf),
            new RepositoryFile("src/Lib/B/Back.g.cs", GeneratedBack));

        FindingAssert.None(findings);
    }

    private static Task<IReadOnlyList<AnalyzerFinding>> RunAsync(params RepositoryFile[] sources) =>
        AnalyzerRunner.RunAsync(new NamespaceGraphAnalyzer(), "Lib", sources, [], TestContext.Current.CancellationToken);
}
