using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Runtime.ExceptionServices;
using CsCheck;
using Great.Parts.Cel.Eng.Difftest.Profile;
using Great.Parts.Cel.Eng.Difftest.Sides;

namespace Great.Parts.Cel.Eng.Difftest.Compare;

/// <summary>
/// How long CsCheck searches for a smaller divergent case: a time in whole seconds, or, for tests, a number of iterations.
/// </summary>
/// <param name="Seconds">The time in seconds, or -1 to count iterations.</param>
/// <param name="Iterations">The number of iterations, or -1 to run for the time.</param>
internal readonly record struct MinimizationLimit(int Seconds, long Iterations)
{
    /// <summary>The limit of a run: 20 seconds.</summary>
    internal static MinimizationLimit Default { get; } = Time(20);

    /// <summary>A time in whole seconds, at least 1.</summary>
    /// <param name="seconds">The seconds.</param>
    internal static MinimizationLimit Time(int seconds) => new(Math.Max(1, seconds), -1);

    /// <summary>A number of iterations, for tests.</summary>
    /// <param name="iterations">The iterations.</param>
    internal static MinimizationLimit Count(long iterations) => new(-1, iterations);
}

/// <summary>
/// Shrinks a divergent case (docs/design/eng-difftest.md, "Outcomes and signatures", "Minimization"). CsCheck runs
/// <c>Sample</c> from the seed of the case with the predicate "the outcomes agree" within the limit and gives the smallest
/// divergent case in its size order: nodes first, then the length of the text. Then, while a child of the root still diverges
/// with the same bindings, the child becomes the case. A failed side ends the minimization with its first exception.
/// </summary>
internal static class Minimizer
{
    /// <summary>Minimizes a divergent case.</summary>
    /// <param name="divergent">The divergent case, generated by <see cref="CaseGenerator"/>.</param>
    /// <param name="diverges">Whether the outcomes of a case diverge. Called on one thread.</param>
    /// <param name="limit">How long CsCheck searches.</param>
    /// <returns>The smallest divergent case found, whose root has no divergent child.</returns>
    /// <exception cref="IOException">The first <see cref="IOException"/> of <paramref name="diverges"/>, after which it is not called again.</exception>
    /// <exception cref="SideFailureException">The first <see cref="SideFailureException"/> of <paramref name="diverges"/>, after which it is not called again.</exception>
    internal static GeneratedCase Minimize(GeneratedCase divergent, Func<GeneratedCase, bool> diverges, MinimizationLimit limit)
    {
        GeneratedCase smallest = divergent;
        (int Nodes, int Length) smallestSize = Size(divergent);
        ExceptionDispatchInfo? failure = null;
        try
        {
            CaseGenerator.Instance.Sample(
                generated =>
                {
                    // Sample would catch the exception of a failed side and go on asking it; the rest of the samples pass
                    // without a call, and the exception goes on after Sample.
                    if (failure is not null)
                    {
                        return true;
                    }

                    bool divergesNow;
                    try
                    {
                        divergesNow = diverges(generated);
                    }
                    catch (Exception exception) when (exception is IOException or SideFailureException)
                    {
                        failure = ExceptionDispatchInfo.Capture(exception);
                        return true;
                    }

                    if (!divergesNow)
                    {
                        return true;
                    }

                    (int Nodes, int Length) size = Size(generated);
                    if (size.CompareTo(smallestSize) < 0)
                    {
                        smallest = generated;
                        smallestSize = size;
                    }

                    return false;
                },
                seed: divergent.Seed,
                iter: limit.Iterations,
                time: limit.Seconds,
                threads: 1);
        }
        catch (CsCheckException)
        {
            // Sample reports the divergence it found by this exception; the smallest case is already kept.
        }

        failure?.Throw();
        GeneratedCase current = smallest;
        while (Children(current.Expression).Select(child => current with { Expression = child }).FirstOrDefault(diverges) is { } child)
        {
            current = child;
        }

        return current;
    }

    /// <summary>The children of a node: the arguments of a call, the elements of a list, the keys and values of a map.</summary>
    /// <param name="node">The node.</param>
    internal static IEnumerable<Expr> Children(Expr node) => node switch
    {
        Call call => call.Args,
        ListLiteral list => list.Elements,
        MapLiteral map => map.Entries.SelectMany(entry => new[] { entry.Key, entry.Value }),
        _ => [],
    };

    // The size order of CsCheck for the generator: the number of nodes, then the length of the text.
    private static (int Nodes, int Length) Size(GeneratedCase generated) => (Nodes(generated.Expression), generated.Text.Length);

    private static int Nodes(Expr node) => 1 + Children(node).Sum(Nodes);
}
